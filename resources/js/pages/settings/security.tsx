import { router, useForm, usePage } from '@inertiajs/react';
import { useCallback, useEffect, useState } from 'react';
import type { FormEvent } from 'react';
import { Alert } from '@/components/ui/alert';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { Input } from '@/components/ui/input';
import { Modal } from '@/components/ui/modal';
import AppLayout from '@/layouts/app-layout';
import { fortify } from '@/lib/fortify';

async function getJson<T>(url: string): Promise<T> {
    const response = await fetch(url, {
        credentials: 'same-origin',
        headers: {
            Accept: 'application/json',
            'X-Requested-With': 'XMLHttpRequest',
        },
    });

    if (!response.ok) {
        throw new Error(`Request failed: ${response.status}`);
    }

    return response.json() as Promise<T>;
}

function PasswordCard() {
    const form = useForm({
        current_password: '',
        password: '',
        password_confirmation: '',
    });

    const submit = (event: FormEvent) => {
        event.preventDefault();
        form.put(fortify.password, {
            errorBag: 'updatePassword',
            preserveScroll: true,
            onSuccess: () => form.reset(),
        });
    };

    return (
        <Card title="Password" description="Use a long, unique password.">
            <form onSubmit={submit} className="max-w-md space-y-4">
                <Input
                    label="Current password"
                    type="password"
                    autoComplete="current-password"
                    value={form.data.current_password}
                    onChange={(e) =>
                        form.setData('current_password', e.target.value)
                    }
                    error={form.errors.current_password}
                />
                <Input
                    label="New password"
                    type="password"
                    autoComplete="new-password"
                    value={form.data.password}
                    onChange={(e) => form.setData('password', e.target.value)}
                    error={form.errors.password}
                />
                <Input
                    label="Confirm new password"
                    type="password"
                    autoComplete="new-password"
                    value={form.data.password_confirmation}
                    onChange={(e) =>
                        form.setData('password_confirmation', e.target.value)
                    }
                    error={form.errors.password_confirmation}
                />
                <div className="flex items-center gap-3">
                    <Button type="submit" loading={form.processing}>
                        Update password
                    </Button>
                    {form.recentlySuccessful && (
                        <span className="text-sm text-success" role="status">
                            Saved.
                        </span>
                    )}
                </div>
            </form>
        </Card>
    );
}

function TwoFactorSetup() {
    const [qr, setQr] = useState<string | null>(null);
    const [secret, setSecret] = useState<string | null>(null);
    const form = useForm({ code: '' });

    useEffect(() => {
        void getJson<{ svg: string }>(fortify.twoFactorQrCode).then((r) =>
            setQr(r.svg),
        );
        void getJson<{ secretKey: string }>(fortify.twoFactorSecretKey).then(
            (r) => setSecret(r.secretKey),
        );
    }, []);

    const submit = (event: FormEvent) => {
        event.preventDefault();
        form.post(fortify.twoFactorConfirm, {
            errorBag: 'confirmTwoFactorAuthentication',
            preserveScroll: true,
        });
    };

    return (
        <div className="space-y-4">
            <Alert variant="info">
                Scan this QR code with an authenticator app, then enter the
                6-digit code to finish.
            </Alert>
            {qr && (
                <div
                    className="w-48 rounded-box bg-white p-2"
                    aria-label="Two-factor QR code"
                    // SVG is generated by Fortify on the server.
                    dangerouslySetInnerHTML={{ __html: qr }}
                />
            )}
            {secret && (
                <p className="text-sm">
                    Can't scan? Enter this key manually:{' '}
                    <code className="font-mono">{secret}</code>
                </p>
            )}
            <form onSubmit={submit} className="max-w-xs space-y-4">
                <Input
                    label="Authentication code"
                    inputMode="numeric"
                    autoComplete="one-time-code"
                    value={form.data.code}
                    onChange={(e) => form.setData('code', e.target.value)}
                    error={form.errors.code}
                />
                <Button type="submit" loading={form.processing}>
                    Confirm and enable
                </Button>
            </form>
        </div>
    );
}

function RecoveryCodes() {
    const [codes, setCodes] = useState<string[] | null>(null);

    const load = useCallback(() => {
        void getJson<string[]>(fortify.recoveryCodes).then(setCodes);
    }, []);

    useEffect(load, [load]);

    const regenerate = () =>
        router.post(
            fortify.recoveryCodes,
            {},
            { preserveScroll: true, onSuccess: load },
        );

    return (
        <div className="space-y-3">
            <p className="text-sm">
                Store these recovery codes in a password manager. Each code can
                be used once if you lose your authenticator.
            </p>
            {codes && (
                <ul className="grid max-w-md gap-1 rounded-box bg-base-200 p-4 font-mono text-sm">
                    {codes.map((code) => (
                        <li key={code}>{code}</li>
                    ))}
                </ul>
            )}
            <Button variant="soft" size="sm" onClick={regenerate}>
                Regenerate recovery codes
            </Button>
        </div>
    );
}

export default function Security() {
    const { auth } = usePage().props;
    const [confirmDisable, setConfirmDisable] = useState(false);
    const [disabling, setDisabling] = useState(false);

    const enable = () =>
        router.post(fortify.twoFactor, {}, { preserveScroll: true });

    const disable = () =>
        router.delete(fortify.twoFactor, {
            preserveScroll: true,
            onStart: () => setDisabling(true),
            onFinish: () => {
                setDisabling(false);
                setConfirmDisable(false);
            },
        });

    return (
        <AppLayout title="Security">
            <Card
                title="Two-factor authentication"
                description="Adds a second step to every login. Strongly recommended: this panel controls your server."
            >
                {auth.twoFactor.enabled ? (
                    <div className="space-y-4">
                        <Alert variant="success">
                            Two-factor authentication is on.
                        </Alert>
                        <RecoveryCodes />
                        <Button
                            variant="error"
                            size="sm"
                            onClick={() => setConfirmDisable(true)}
                        >
                            Disable two-factor authentication
                        </Button>
                    </div>
                ) : auth.twoFactor.pending ? (
                    <TwoFactorSetup />
                ) : (
                    <div className="space-y-4">
                        <Alert variant="warning">
                            Two-factor authentication is off.
                        </Alert>
                        <Button onClick={enable}>Enable</Button>
                    </div>
                )}
            </Card>

            <PasswordCard />

            <Modal
                open={confirmDisable}
                onClose={() => setConfirmDisable(false)}
                title="Disable two-factor authentication?"
                size="sm"
                footer={
                    <>
                        <Button
                            variant="ghost"
                            onClick={() => setConfirmDisable(false)}
                        >
                            Cancel
                        </Button>
                        <Button
                            variant="error"
                            loading={disabling}
                            onClick={disable}
                        >
                            Disable
                        </Button>
                    </>
                }
            >
                Your account will be protected by your password only.
            </Modal>
        </AppLayout>
    );
}
